"""JWT issuance + the FastAPI dependencies that consume them.

Tokens carry an optional `jti` claim that maps to a Session row. Sessions
let users see their devices and revoke individual logins from the Settings
page. Tokens issued before the sessions table existed have no jti and skip
the lookup — those still work but can't be individually revoked.
"""

from datetime import datetime, timedelta, timezone
from typing import Optional

from fastapi import Depends, HTTPException, Request, status
from fastapi.security import HTTPBearer, HTTPAuthorizationCredentials
from jose import jwt, JWTError, ExpiredSignatureError
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import settings
from app.database import get_db
from app.models.session import Session
from app.models.user import User

security = HTTPBearer(auto_error=False)


def create_access_token(user_id: str, email: str, session_id: Optional[str] = None) -> str:
    """Create a signed JWT.

    Pass `session_id` (a Session.id, generated by the route before calling)
    to enable per-token revocation. Tokens without it still validate but
    can't be revoked individually.
    """
    expire = datetime.now(timezone.utc) + timedelta(minutes=settings.JWT_EXPIRATION_MINUTES)
    payload: dict[str, object] = {"sub": user_id, "email": email, "exp": expire}
    if session_id:
        payload["jti"] = session_id
    return jwt.encode(payload, settings.JWT_SECRET, algorithm=settings.JWT_ALGORITHM)


def _decode_token(credentials: Optional[HTTPAuthorizationCredentials]) -> dict:
    if not credentials:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Not authenticated",
            headers={"WWW-Authenticate": "Bearer"},
        )
    try:
        payload = jwt.decode(
            credentials.credentials,
            settings.JWT_SECRET,
            algorithms=[settings.JWT_ALGORITHM],
        )
    except ExpiredSignatureError:
        raise HTTPException(status_code=401, detail="Token expired")
    except JWTError:
        raise HTTPException(status_code=401, detail="Invalid token")
    if not payload.get("sub"):
        raise HTTPException(status_code=401, detail="Invalid token payload")
    return payload


async def _validate_session(
    payload: dict,
    db: AsyncSession,
    request: Optional[Request] = None,
) -> None:
    """If the token has a jti, the matching session must exist + not be revoked.
    Mutates last_used_at as a side-effect so the Settings page can show
    "this device was last used 5 minutes ago"."""
    jti = payload.get("jti")
    if not jti:
        return  # legacy token, skip
    session = await db.get(Session, jti)
    if session is None:
        raise HTTPException(status_code=401, detail="Session no longer exists")
    if session.revoked_at is not None:
        raise HTTPException(status_code=401, detail="Session was revoked")
    session.last_used_at = datetime.now(timezone.utc)
    # Caller commits — we don't want to commit on every request just for
    # an audit field, so leave the transaction handling to the surrounding
    # request lifecycle. This makes last_used_at lag by a request, which
    # is fine for UI.


async def get_current_user(
    request: Request,
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(security),
    db: AsyncSession = Depends(get_db),
) -> User:
    payload = _decode_token(credentials)
    await _validate_session(payload, db, request)

    user = await db.get(User, payload["sub"])
    if not user:
        raise HTTPException(status_code=401, detail="User not found")
    if user.deleted_at is not None:
        raise HTTPException(status_code=401, detail="Account deleted")
    if user.deactivated_at is not None:
        raise HTTPException(
            status_code=423,
            detail="Account deactivated. Reactivate via /api/auth/me/reactivate.",
        )
    return user


async def get_current_user_allow_deactivated(
    request: Request,
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(security),
    db: AsyncSession = Depends(get_db),
) -> User:
    """Like get_current_user but accepts deactivated accounts.

    Used only by the reactivate / fetch-self endpoints so a deactivated user
    can see their own state and lift the suspension. Still rejects deleted
    accounts and revoked sessions.
    """
    payload = _decode_token(credentials)
    await _validate_session(payload, db, request)

    user = await db.get(User, payload["sub"])
    if not user or user.deleted_at is not None:
        raise HTTPException(status_code=401, detail="User not found")
    return user


# ─── SSE stream tickets ───────────────────────────────────────────────────
#
# The browser ``EventSource`` API can't attach Authorization headers, so the
# SSE pipeline endpoints can't take a Bearer JWT directly. We trade-and-burn
# instead: an authenticated client POSTs to ``/.../stream-ticket`` and gets
# back a short-lived (60s) JWT bound to (user_id, resource_kind, resource_id).
# That ticket is passed as ``?ticket=...`` on the SSE URL — limited blast
# radius if it ever leaks (one-resource scope, expires in seconds, can't
# itself be exchanged for a session token).

_STREAM_TICKET_TTL_SECONDS = 60


def create_stream_ticket(user_id: str, resource_kind: str, resource_id: str) -> str:
    """Issue a short-lived JWT that authorizes a single SSE stream open."""
    expire = datetime.now(timezone.utc) + timedelta(seconds=_STREAM_TICKET_TTL_SECONDS)
    payload = {
        "sub": user_id,
        "kind": resource_kind,
        "rid": resource_id,
        "exp": expire,
        "type": "stream",
    }
    return jwt.encode(payload, settings.JWT_SECRET, algorithm=settings.JWT_ALGORITHM)


def decode_stream_ticket(ticket: str, resource_kind: str, resource_id: str) -> str:
    """Validate a stream ticket and return the user_id it was issued to.

    Raises 401 on bad/expired ticket, 403 if the ticket was issued for a
    different resource — the caller doesn't get to use someone else's
    ticket on this stream.
    """
    try:
        payload = jwt.decode(
            ticket, settings.JWT_SECRET, algorithms=[settings.JWT_ALGORITHM]
        )
    except ExpiredSignatureError:
        raise HTTPException(status_code=401, detail="Stream ticket expired")
    except JWTError:
        raise HTTPException(status_code=401, detail="Invalid stream ticket")
    if payload.get("type") != "stream":
        raise HTTPException(status_code=401, detail="Wrong ticket type")
    if payload.get("kind") != resource_kind or payload.get("rid") != resource_id:
        raise HTTPException(status_code=403, detail="Ticket not valid for this resource")
    user_id = payload.get("sub")
    if not user_id:
        raise HTTPException(status_code=401, detail="Invalid ticket payload")
    return user_id


async def get_current_user_optional(
    request: Request,
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(security),
    db: AsyncSession = Depends(get_db),
) -> Optional[User]:
    """Same as get_current_user but returns None if no/invalid token —
    for endpoints that work with or without auth (e.g. public shared reports)."""
    if not credentials:
        return None
    try:
        payload = jwt.decode(
            credentials.credentials,
            settings.JWT_SECRET,
            algorithms=[settings.JWT_ALGORITHM],
        )
        if not payload.get("sub"):
            return None
        # Best-effort session check — silently treat revoked tokens as
        # unauthenticated rather than 401 here, to match this dep's contract.
        jti = payload.get("jti")
        if jti:
            session = await db.get(Session, jti)
            if session is None or session.revoked_at is not None:
                return None
        return await db.get(User, payload["sub"])
    except (ExpiredSignatureError, JWTError):
        return None
