"use client";

import { use, useEffect, useState } from "react";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Shield, FileText, Loader2 } from "lucide-react";

const BACKEND_URL = process.env.NEXT_PUBLIC_BACKEND_URL || "http://localhost:8000";

interface SharedReport {
  id: string;
  report_type: string;
  title: string;
  summary: string | null;
  created_at: string;
}

export default function SharedReportPage({
  params,
}: {
  params: Promise<{ shareToken: string }>;
}) {
  const { shareToken } = use(params);
  const [report, setReport] = useState<SharedReport | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);

  useEffect(() => {
    fetch(`${BACKEND_URL}/api/reports/shared/${shareToken}`)
      .then((r) => {
        if (!r.ok) throw new Error("Not found");
        return r.json();
      })
      .then(setReport)
      .catch(() => setError(true))
      .finally(() => setLoading(false));
  }, [shareToken]);

  if (loading) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-zinc-950">
        <Loader2 className="h-8 w-8 animate-spin text-emerald-400" />
      </div>
    );
  }

  if (error || !report) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-zinc-950 p-4">
        <Card className="w-full max-w-lg border-zinc-800 bg-zinc-900/50">
          <CardContent className="py-12 text-center">
            <Shield className="mx-auto mb-4 h-12 w-12 text-zinc-600" />
            <h1 className="text-xl font-bold text-white">Report Not Found</h1>
            <p className="mt-2 text-sm text-zinc-400">
              This shared report link may have expired or does not exist.
            </p>
          </CardContent>
        </Card>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-zinc-950 p-4 md:p-8">
      <div className="mx-auto max-w-3xl">
        {/* Header */}
        <div className="mb-6 flex items-center justify-center gap-2">
          <Shield className="h-6 w-6 text-emerald-400" />
          <span className="text-lg font-bold text-white">ArtiProof</span>
        </div>

        <Card className="border-zinc-800 bg-zinc-900/50">
          <CardContent className="py-8">
            <div className="text-center">
              <FileText className="mx-auto mb-3 h-10 w-10 text-emerald-400" />
              <h1 className="text-2xl font-bold text-white">{report.title}</h1>
              <div className="mt-2 flex items-center justify-center gap-2">
                <Badge className={
                  report.report_type === "source_verification"
                    ? "bg-emerald-500/20 text-emerald-400"
                    : "bg-purple-500/20 text-purple-400"
                }>
                  {report.report_type === "source_verification" ? "Source Verification" : "Researcher Integrity"}
                </Badge>
                <span className="text-xs text-zinc-500">
                  {new Date(report.created_at).toLocaleDateString()}
                </span>
              </div>
            </div>

            {report.summary && (
              <div className="mt-8">
                <h2 className="mb-3 text-sm font-semibold text-zinc-400">Executive Summary</h2>
                <div className="space-y-3">
                  {report.summary.split("\n\n").map((para, i) => (
                    para.trim() && (
                      <p key={i} className="text-sm leading-relaxed text-zinc-300">
                        {para}
                      </p>
                    )
                  ))}
                </div>
              </div>
            )}

            <div className="mt-8 text-center">
              <p className="text-xs text-zinc-500">
                This report was generated by ArtiProof Research Integrity Platform
              </p>
            </div>
          </CardContent>
        </Card>
      </div>
    </div>
  );
}
